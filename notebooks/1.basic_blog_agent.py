from __future__ import annotations

import operator
from typing import TypedDict, List, Annotated

from pydantic import BaseModel, Field
from langgraph.graph import StateGraph, START, END
from langgraph.types import Send
import os
from langchain_groq import ChatGroq
from langchain_core.messages import SystemMessage, HumanMessage

import psycopg
from psycopg.rows import dict_row
from langgraph.checkpoint.postgres import PostgresSaver

from dotenv import load_dotenv

from rich import print

load_dotenv()


def get_database_url():
    database_url = os.getenv("DATABASE_URL")

    if not database_url:
        raise ValueError(
            "DATABASE_URL is missing. Please add your Render PostgreSQL External Database URL to .env"
        )

    if "sslmode=" not in database_url:
        separator = "&" if "?" in database_url else "?"
        database_url = f"{database_url}{separator}sslmode=require"

    return database_url


GROQ_API_KEY = os.getenv("GROQ_API_KEY")
if not GROQ_API_KEY:
    raise ValueError("GROQ_API_KEY is missing. Please add it to your .env file.")


class Task(BaseModel):
    id: int
    title: str
    brief: str = Field(..., description="What to cover")

class Plan(BaseModel):
    blog_title: str
    tasks: List[Task]


class State(TypedDict):
    topic: str
    plan: Plan
    # reducer: results from workers get concatenated automatically
    sections: Annotated[List[str], operator.add]
    final: str

llm = ChatGroq(
    model="openai/gpt-oss-120b",
    api_key=GROQ_API_KEY
)    

def orchestrator(state: State) -> dict:

    plan = llm.with_structured_output(Plan).invoke(
        [
            SystemMessage(
                content=(
                    "Create a blog plan with 5-7 sections on the following topic."
                )
            ),
            HumanMessage(content=f"Topic: {state['topic']}"),
        ]
    )
    return {"plan": plan}

# Distributing work into multiple smaller tasks.
def fanout(state: State):
    return [
        Send("worker", {
            "task": task,
            "topic": state["topic"],
            "plan": state["plan"]
        })
        for task in state["plan"].tasks
    ]


def worker(payload: dict) -> dict:
    # payload contains what we sent
    task = payload["task"]
    topic = payload["topic"]
    plan = payload["plan"]

    blog_title = plan.blog_title

    section_md = llm.invoke(
        [
            SystemMessage(content="Write one clean Markdown section."),
            HumanMessage(
                content=(
                    f"Blog: {blog_title}\n"
                    f"Topic: {topic}\n\n"
                    f"Section: {task.title}\n"
                    f"Brief: {task.brief}\n\n"
                    "Return only the section content in Markdown."
                )
            ),
        ]
    ).content.strip()

    return {"sections": [section_md]}


from pathlib import Path
import re

def reducer(state: State) -> dict:
    title = state["plan"].blog_title
    sections = state.get("sections", [])

    print(f"\nGenerated sections: {len(sections)}")

    if not sections:
        raise ValueError("No sections were generated by the workers.")

    # Combine all generated sections
    body = "\n\n".join(sections).strip()

    # Create the final Markdown content
    final_md = f"# {title}\n\n{body}\n"

    # Save directly in the same directory as this Python file
    safe_title = re.sub(r'[<>:"/\\|?*]', "", title)
    safe_title = re.sub(r"\s+", "_", safe_title).strip("._")

    filename = f"{safe_title}.md"
    output_path = Path(__file__).resolve().parent / filename

    # Write the Markdown file
    output_path.write_text(final_md, encoding="utf-8")

    print("\nBlog saved successfully!")
    print(f"File location: {output_path.resolve()}")
    print(f"Content length: {len(final_md)} characters")

    return {"final": final_md}



graph = StateGraph(State)
graph.add_node("orchestrator", orchestrator)
graph.add_node("worker", worker)
graph.add_node("reducer", reducer)

graph.add_edge(START, "orchestrator")
graph.add_conditional_edges("orchestrator", fanout, ["worker"])
graph.add_edge("worker", "reducer")
graph.add_edge("reducer", END)


# =========================
# PostgreSQL Checkpointer
# =========================
DATABASE_URL = get_database_url()

_conn = psycopg.connect(
    DATABASE_URL,
    autocommit=True,
    row_factory=dict_row
)

checkpointer = PostgresSaver(_conn)
checkpointer.setup()


app = graph.compile(checkpointer=checkpointer)


config = {
        "configurable": {
            "thread_id": "test_thread_id"
        }
    }
final_state = app.invoke({"topic": "Write a blog on Self Attention", "sections": []}, config=config)

print(final_state)

